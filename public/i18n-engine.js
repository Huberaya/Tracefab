  // Safe element text replacement by data-i18n attribute or direct mapping
  window.applyLanguage = function (lang) {
    if (!SUPPORTED_LANGS.includes(lang)) lang = 'en';
    currentLang = lang;
    localStorage.setItem('tracefab_lang', lang);
    document.documentElement.lang = lang;

    const dict = UI_DICTIONARY[lang] || UI_DICTIONARY.en;

    // Apply to elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    // Update indicator button if present
    const codeIndicator = document.getElementById('current-lang-code');
    if (codeIndicator) {
      codeIndicator.textContent = lang.toUpperCase();
    }

    // Update select element if present
    const select = document.getElementById('globalLangSelector');
    if (select) {
      select.value = lang;
    }
  };

  window.setLanguage = function (lang) {
    window.applyLanguage(lang);
    const menu = document.getElementById('lang-dropdown-menu');
    if (menu) menu.style.display = 'none';
  };

  window.toggleLangMenu = function () {
    const menu = document.getElementById('lang-dropdown-menu');
    if (menu) {
      menu.style.display = menu.style.display === 'block' ? 'none' : 'block';
    }
  };

  // Auto-init on load
  document.addEventListener('DOMContentLoaded', function () {
    const saved = localStorage.getItem('tracefab_lang') || 'en';
    window.applyLanguage(saved);
  });
