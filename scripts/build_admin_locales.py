def used_keys():
    """Extrait les clés réellement appelées par admin/index.html.

    Le script est la source de vérité : si une clé est ajoutée au composant sans
    traduction, la génération échoue au lieu de laisser l'interface afficher la
    clé brute en production.
    """
    import re
    html = open(os.path.join(root, "admin", "index.html"), encoding="utf-8").read()
    keys = set(re.findall(r"\bt\('([a-zA-Z.]+)'\)", html))
    dynamic = {
        "stage.": ["new","qualified","to_contact","contacted","replied","meeting","demo","pilot","customer","lost"],
        "priority.": ["critical","high","medium","low"],
        "type.": ["fashion_brand","textile_brand","manufacturer","textile_supplier","mill","dye_house",
                  "garment_factory","luxury_brand","sportswear","outdoor","retailer","marketplace","other"],
        "maturity.": ["unknown","low","medium","high"],
        "contactStatus.": ["to_contact","contacted","replied","meeting","unresponsive","declined"],
        "activity.": ["created","status_change","note","email","call","meeting","demo","proposal","pilot","conversion","lost"],
        "nav.": ["dashboard","prospects","pipeline","contacts",
                 # Chantier Admin 02 — construites par NAV_OPS.map(id => t('nav.' + id))
                 "tasks","activities","meetings","pilots","customers","analytics"],
        "taskType.": ["call","email","follow_up","book_demo","prepare_demo","send_proposal","follow_pilot","other"],
        "meetMode.": ["onsite","video","call"],
        "pilotStatus.": ["planned","active","completed","abandoned"],
        # Construites par le helper kpi() : t('dashboard.' + key)
        "dashboard.": ["prospects","new","toContact","contacted","replies","meetings",
                       "demos","pilots","customers","lost","value","conversion","dueToday",
                       # passées à bars() puis à t(title)
                       "byStage","byCountry","byType","byPriority"],
    }
    for prefix, values in dynamic.items():
        for v in values:
            keys.add(prefix + v)
    return sorted(k for k in keys if "." in k)

