#!/usr/bin/env node
/**
 * Exécute la correction PLM/GS1 sur un PostgreSQL 17 jetable.
 *
 * Le test crée une base dédiée sur le seul service PostgreSQL local CI,
 * reproduit le catalogue Neon mesuré (quatre CHECK PLM absents et CHECK GS1
 * historique sans GPC), applique la migration, vérifie les refus métier,
 * puis rejoue la migration pour prouver son idempotence.
 */
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migrationPath = path.join(
  root,
  'prisma/migrations/20261104090000_plm_integrations_and_gs1_constraints/migration.sql',
);
const source = process.env.DATABASE_URL;
assert.ok(source, 'DATABASE_URL obligatoire');
assert.equal(process.env.TF_EXIGER_LOCAL, 'oui', 'TF_EXIGER_LOCAL=oui obligatoire');

const sourceUrl = new URL(source);
assert.ok(['127.0.0.1', 'localhost', '::1'].includes(sourceUrl.hostname),
  'refus : le test accepte uniquement PostgreSQL local');
assert.equal(sourceUrl.pathname.replace(/^\//, ''), 'tracefab_test',
  'refus : la base source doit être tracefab_test');

const dbName = 'tf_plm_gs1_' + randomBytes(6).toString('hex');
const adminUrl = new URL(sourceUrl);
adminUrl.pathname = '/postgres';
adminUrl.searchParams.delete('schema');
const testUrl = new URL(sourceUrl);
testUrl.pathname = '/' + dbName;
testUrl.searchParams.delete('schema');

const admin = new pg.Client({ connectionString: adminUrl.toString() });
let client;
let created = false;
let echecs = 0;
function ok(label, condition, detail = '') {
  if (condition) console.log('  ok    ' + label);
  else {
    echecs += 1;
    console.error('  ECHEC ' + label + (detail ? ' — ' + detail : ''));
  }
}
async function refuse(sql, label) {
  await client.query('SAVEPOINT expected_rejection');
  let error = null;
  try {
    await client.query(sql);
  } catch (e) {
    error = e;
  }
  await client.query('ROLLBACK TO SAVEPOINT expected_rejection');
  await client.query('RELEASE SAVEPOINT expected_rejection');
  ok(label, Boolean(error && error.code === '23514'), error?.message || 'écriture acceptée');
}

try {
  await admin.connect();
  await admin.query('CREATE DATABASE "' + dbName + '"');
  created = true;
  client = new pg.Client({ connectionString: testUrl.toString() });
  await client.connect();

  await client.query(`
    CREATE TABLE public.plm_erp_integrations (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      system_type text NOT NULL,
      name text NOT NULL,
      auth_type text NOT NULL DEFAULT 'api_key',
      status text NOT NULL DEFAULT 'active'
    );
    CREATE TABLE public.product_identifiers (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      identifier_type text NOT NULL,
      CONSTRAINT product_identifiers_identifier_type_check
        CHECK (identifier_type IN ('gtin', 'ean', 'upc', 'internal', 'gs1_digital_link', 'gln'))
    );
    INSERT INTO public.plm_erp_integrations (system_type, name, auth_type, status)
      VALUES ('centric_plm', 'fixture-valid', 'api_key', 'active');
    INSERT INTO public.product_identifiers (identifier_type) VALUES ('gtin');
  `);

  const before = await client.query(`
    SELECT
      (SELECT count(*)::int FROM pg_constraint
       WHERE conrelid='public.plm_erp_integrations'::regclass
         AND conname IN ('plm_erp_integrations_system_type_check','plm_erp_integrations_name_check',
                         'plm_erp_integrations_auth_type_check','plm_erp_integrations_status_check')) AS plm_checks,
      (SELECT pg_get_constraintdef(oid) FROM pg_constraint
       WHERE conrelid='public.product_identifiers'::regclass
         AND conname='product_identifiers_identifier_type_check') AS identifier_check
  `);
  ok('fixture : les quatre CHECK PLM sont absents', before.rows[0].plm_checks === 0);
  ok('fixture : la contrainte GS1 historique ne contient pas GPC',
    !before.rows[0].identifier_check.includes('gpc'), before.rows[0].identifier_check);

  const migration = readFileSync(migrationPath, 'utf8');
  await client.query(migration);

  const after = await client.query(`
    SELECT
      (SELECT count(*)::int FROM pg_constraint
       WHERE conrelid='public.plm_erp_integrations'::regclass
         AND contype='c' AND convalidated
         AND conname IN ('plm_erp_integrations_system_type_check','plm_erp_integrations_name_check',
                         'plm_erp_integrations_auth_type_check','plm_erp_integrations_status_check')) AS plm_checks,
      (SELECT pg_get_constraintdef(oid) FROM pg_constraint
       WHERE conrelid='public.product_identifiers'::regclass
         AND conname='product_identifiers_identifier_type_check') AS identifier_check
  `);
  ok('quatre CHECK PLM ajoutés et validés', after.rows[0].plm_checks === 4,
    String(after.rows[0].plm_checks));
  ok('la contrainte GS1 inclut GPC', after.rows[0].identifier_check.includes('gpc'),
    after.rows[0].identifier_check);

  await client.query("INSERT INTO public.product_identifiers (identifier_type) VALUES ('gpc')");
  await refuse("INSERT INTO public.plm_erp_integrations (system_type,name,auth_type,status) VALUES ('invalid','x','api_key','active')",
    'system_type invalide refusé');
  await refuse("INSERT INTO public.plm_erp_integrations (system_type,name,auth_type,status) VALUES ('centric_plm','   ','api_key','active')",
    'nom vide refusé');
  await refuse("INSERT INTO public.plm_erp_integrations (system_type,name,auth_type,status) VALUES ('centric_plm','x','invalid','active')",
    'auth_type invalide refusé');
  await refuse("INSERT INTO public.plm_erp_integrations (system_type,name,auth_type,status) VALUES ('centric_plm','x','api_key','invalid')",
    'status invalide refusé');
  await refuse("INSERT INTO public.product_identifiers (identifier_type) VALUES ('invalid')",
    'type d’identifiant invalide refusé');

  await client.query(migration);
  const final = await client.query(`
    SELECT
      (SELECT count(*)::int FROM public.plm_erp_integrations) AS plm_rows,
      (SELECT count(*)::int FROM public.product_identifiers) AS identifier_rows,
      (SELECT count(*)::int FROM pg_constraint
       WHERE conrelid='public.plm_erp_integrations'::regclass
         AND contype='c' AND convalidated
         AND conname IN ('plm_erp_integrations_system_type_check','plm_erp_integrations_name_check',
                         'plm_erp_integrations_auth_type_check','plm_erp_integrations_status_check')) AS plm_checks
  `);
  ok('rejeu idempotent sans perte de données', final.rows[0].plm_rows === 1
    && final.rows[0].identifier_rows === 2 && final.rows[0].plm_checks === 4,
    JSON.stringify(final.rows[0]));
} catch (error) {
  console.error('ECHEC — ' + (error.stack || error.message));
  process.exitCode = 1;
} finally {
  if (client) {
    try { await client.end(); } catch (error) {
      console.error('fermeture base test : ' + error.message);
      process.exitCode = 1;
    }
  }
  if (created) {
    try { await admin.query('DROP DATABASE IF EXISTS "' + dbName + '"'); } catch (error) {
      console.error('NETTOYAGE base test : ' + error.message);
      process.exitCode = 1;
    }
  }
  try { await admin.end(); } catch {}
}
if (echecs > 0) process.exitCode = 1;
else console.log('\n  PASS — correction PLM/GS1 validée sur PostgreSQL réel, refus métier et rejeu idempotent.\n');
